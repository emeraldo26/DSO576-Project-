def grid(headers, data, widths, compact=False):
    tab = Table([[p(v, 'small') for v in headers]] + [[p(v, 'small') for v in row] for row in data], colWidths=widths, repeatRows=1, hAlign='LEFT')
    tab.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#e6edf2')),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('LINEBELOW', (0, 0), (-1, 0), .6, colors.HexColor('#73889a')),
        ('LINEBELOW', (0, 1), (-1, -1), .3, colors.HexColor('#d4dce1')),
        ('LEFTPADDING', (0, 0), (-1, -1), 6), ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 3 if compact else 6), ('BOTTOMPADDING', (0, 0), (-1, -1), 3 if compact else 5)]))
    story.append(tab)
    story.append(Spacer(1, 8))
def page(title):
    story.append(PageBreak())
